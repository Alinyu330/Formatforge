function decryptKeyByMask(key: Uint8Array, mask: Uint8Array): Uint8Array {
  const result = new Uint8Array(key.length);
  for (let i = 0; i < key.length; i++) {
    result[i] = key[i] ^ mask[i % mask.length];
  }
  return result;
}

function getKeyFromSeed(seed: number): Uint8Array {
  const keyLen = 1024;
  const key = new Uint8Array(keyLen);
  for (let i = 0; i < keyLen; i++) {
    seed = (seed * 299 + 43) & 0xFFFF;
    key[i] = seed & 0xFF;
  }
  return key;
}

// QMCv1 formats (QMC0, QMC3, QMCflac)
export async function decryptQMC(data: Uint8Array): Promise<{ data: Uint8Array; ext: string }> {
  // Detect format version
  const isQmc2 = data.length > 4 &&
    (data[0] === 0x6D && data[1] === 0x67 && data[2] === 0x67 ||  // mgg
     data[0] === 0x6D && data[1] === 0x66 && data[2] === 0x6C);    // mflac

  let offset = 4;
  let ext = 'mp3';

  if (isQmc2) {
    // QMCv2 - MGG/MFLAC: header is 4+4 bytes, then encrypted data
    offset = 8;
    ext = data[0] === 0x6D && data[1] === 0x66 ? 'flac' : 'ogg';
  } else {
    // QMCv1: first byte is key seed index, or 4-byte header
    // Check for 4-byte QMC header
    if (data[0] === 0x51 && (data[1] & 0xFC) === 0x4D) {
      // QMC0/QMC3/QMCflac: has 4-byte header
      offset = 4;
      // Try different key derivation methods
      // For simple QMC, the first byte after header can indicate format
    } else if (data[0] === 0x51 && data[1] === 0x4D && data[2] === 0x43) {
      offset = 4;
    }
  }

  // Extract the encrypted audio
  const audioData = data.slice(offset);

  // Try to determine seed
  let seed = 0;
  if (data.length > 0) {
    seed = data[offset - 1] || 0;
  }

  // Try decrypting with the known static cipher pattern
  const cipher = isQmc2 ? MGG_STATIC_CIPHER : QMC_STATIC_CIPHER;

  // For QMCv1, apply XOR with the static cipher
  const decrypted = new Uint8Array(audioData.length);
  const cipherLen = cipher.length;
  for (let i = 0; i < audioData.length; i++) {
    decrypted[i] = audioData[i] ^ cipher[i % cipherLen];
  }

  // Detect actual format from decrypted header magic bytes
  ext = detectAudioFormat(decrypted);

  return { data: decrypted, ext };
}

function detectAudioFormat(data: Uint8Array): string {
  if (data.length < 4) return 'mp3';

  // FLAC: fLaC
  if (data[0] === 0x66 && data[1] === 0x4C && data[2] === 0x61 && data[3] === 0x43) return 'flac';
  // OGG: OggS
  if (data[0] === 0x4F && data[1] === 0x67 && data[2] === 0x67 && data[3] === 0x53) return 'ogg';
  // WAV: RIFF
  if (data[0] === 0x52 && data[1] === 0x49 && data[2] === 0x46 && data[3] === 0x46) return 'wav';
  // MP3: 0xFF 0xFB / 0xFF 0xF3 / 0xFF 0xF2 / ID3
  if ((data[0] === 0xFF && (data[1] & 0xE0) === 0xE0) || (data[0] === 0x49 && data[1] === 0x44 && data[2] === 0x33)) return 'mp3';
  // AAC: 0xFF 0xF1 / 0xFF 0xF9
  if (data[0] === 0xFF && (data[1] & 0xF6) === 0xF0) return 'aac';
  // M4A: ftyp
  if (data[4] === 0x66 && data[5] === 0x74 && data[6] === 0x79 && data[7] === 0x70) return 'm4a';

  return 'mp3';
}

// Check if a file is QMC-encrypted
export function isQMCFile(filename: string): boolean {
  const ext = filename.split('.').pop()?.toLowerCase() || '';
  return ['qmc0', 'qmc3', 'qmc4', 'qmc6', 'qmc8', 'qmcflac', 'mgg', 'mflac', 'mflac0', 'mgg1', 'bkcmp3', 'bkcflac', 'tkm', 'tkm3', 'tkm4'].includes(ext);
}

// Get the expected decrypted extension
export function getQMCExt(filename: string): string {
  const ext = filename.split('.').pop()?.toLowerCase() || '';
  if (ext.includes('flac') || ext === 'bkcflac') return 'flac';
  if (ext === 'mgg' || ext === 'mgg1') return 'ogg';
  return 'mp3';
}
